// Writes src/zone-coordinates.js: the principal location of every IANA time zone,
// from the tz database's zone.tab (public domain). Run when the tz data changes:
//   node scripts/zone-coordinates.mjs [/usr/share/zoneinfo/zone.tab]
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] || '/usr/share/zoneinfo/zone.tab';
// ISO 6709 in zone.tab: ±DDMM[SS]±DDDMM[SS].
const degrees = (text, width) => {
  const sign = text[0] === '-' ? -1 : 1, d = text.slice(1);
  const deg = Number(d.slice(0, width)), min = Number(d.slice(width, width + 2)), sec = Number(d.slice(width + 2) || 0);
  return Math.round(sign * (deg + min / 60 + sec / 3600) * 100) / 100;
};

const zones = {};
for (const line of readFileSync(source, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coords, zone] = line.split('\t');
  const [, lat, lon] = coords.match(/^([+-]\d+)([+-]\d+)$/);
  zones[zone] = [degrees(lat, 2), degrees(lon, 3)];
}

const body = Object.entries(zones).sort().map(([zone, [lat, lon]]) => `'${zone}':[${lat},${lon}]`).join(',\n');
writeFileSync(new URL('../src/zone-coordinates.js', import.meta.url),
  `// Generated by scripts/zone-coordinates.mjs from the tz database's zone.tab. Do not edit.\n// [latitude, longitude] of each time zone's principal location.\nexport default {\n${body},\n};\n`);
console.log(`Wrote ${Object.keys(zones).length} zones.`);
